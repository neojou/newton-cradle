package com.neojou.newtoncradle.ui

import de.fabmax.kool.util.GeneratorGlyphSet
import de.fabmax.kool.util.MsdfFontGenerator
import kotlinx.coroutines.runBlocking
import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * Builds the Noto Sans TC MSDF atlas once and embeds its JSON for both targets.
 * Later runs only check that the committed files are still present.
 */
class NotoSansTcAtlasTest {
    @Test
    fun atlasCoversTheUiCopy() {
        val fonts = repoFile("composeApp/src/commonMain/resources/assets/fonts")
        fonts.mkdirs()
        val png = File(fonts, "noto-sans-tc.png")
        val json = File(fonts, "noto-sans-tc.json")
        val embedded = repoFile("composeApp/src/commonMain/kotlin/com/neojou/newtoncradle/ui/NotoSansTcFont.kt")
        val jsonText = if (json.isFile) json.readText() else ""
        val missingGlyph = UiText.glyphSource.any { char ->
            char.code > 126 && !jsonText.contains("\"cd\":${char.code}")
        }
        if (!png.exists() || !json.exists() || png.length() < 10_000 || missingGlyph) {
            val otf = repoFile("composeApp/src/commonMain/composeResources/font/notosanstc_regular.otf")
            assertTrue(otf.isFile, "missing font ${otf.absolutePath}")
            val stem = File(fonts, "noto-sans-tc")
            runBlocking {
                MsdfFontGenerator.writeMsdfFont(
                    inputTtfPath = otf.absolutePath,
                    outputMsdfPath = stem.absolutePath,
                    fontName = "Noto Sans TC",
                    glyphsToGenerate = GeneratorGlyphSet.FromString(UiText.glyphSource),
                    msdfGenSize = 32,
                    pxRange = 6.0,
                    atlasDim = 1024,
                )
            }
        }
        assertTrue(png.isFile && png.length() > 10_000, "atlas png missing at ${png.absolutePath}")
        assertTrue(json.isFile, "atlas json missing at ${json.absolutePath}")
        val meta = json.readText()
        assertTrue(meta.contains("29275"), "missing 牛 (U+725B) in atlas json")
        assertTrue(meta.contains("\"cd\":28151"), "missing 混 (U+6DF7) in atlas json")
        if (!embedded.isFile || missingGlyph || !embedded.readText().contains("\"cd\":28151")) {
            writeEmbed(embedded, meta)
        }
        assertTrue(embedded.isFile, "embedded font source missing")
        assertTrue(embedded.readText().contains("\"cd\":28151"))
        if (!missingGlyph) {
            assertTrue(NotoSansTcFont.info.fontMeta.compactGlyphs.any { it.cd == 29275 })
            assertTrue(NotoSansTcFont.info.fontMeta.compactGlyphs.any { it.cd == 28151 })
        }
    }

    private fun writeEmbed(target: File, json: String) {
        val escaped = json.trim().replace("$", "\${'$'}")
        assertTrue(!escaped.contains("\"\"\""), "font json contains a raw-string terminator")
        target.parentFile.mkdirs()
        target.writeText(
            """
            package com.neojou.newtoncradle.ui

            import de.fabmax.kool.util.MsdfFontInfo
            import de.fabmax.kool.util.MsdfMeta
            import kotlinx.serialization.json.Json

            /** Generated by NotoSansTcAtlasTest from assets/fonts/noto-sans-tc.json. */
            internal object NotoSansTcFont {
                const val TEXTURE_PATH = "assets/fonts/noto-sans-tc.png"
                val info: MsdfFontInfo by lazy {
                    val meta = Json.decodeFromString(MsdfMeta.serializer(), META_JSON)
                    MsdfFontInfo(meta, TEXTURE_PATH)
                }

                private const val META_JSON = ""${'"'}$escaped""${'"'}
            }
            """.trimIndent() + "\n",
        )
    }

    private fun repoFile(relative: String): File {
        var dir = File(System.getProperty("user.dir")).absoluteFile
        repeat(5) {
            val candidate = File(dir, relative)
            if (candidate.exists() || File(dir, "settings.gradle.kts").exists()) {
                return candidate
            }
            dir = dir.parentFile ?: return candidate
        }
        return File(relative)
    }
}
